CREATE TABLE offer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    discount_percent NUMERIC(5, 2) NOT NULL CHECK (discount_percent > 0 AND discount_percent <= 100),
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (ends_at > starts_at)
);

CREATE TABLE coupon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_code VARCHAR(40) NOT NULL UNIQUE,
    offer_id BIGINT NOT NULL REFERENCES offer(id) ON DELETE CASCADE,
    usage_limit INTEGER NOT NULL CHECK (usage_limit > 0),
    usage_count INTEGER NOT NULL DEFAULT 0 CHECK (usage_count >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (usage_count <= usage_limit)
);

CREATE TABLE coupon_redemption (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id BIGINT NOT NULL REFERENCES coupon(id) ON DELETE RESTRICT,
    customer_id BIGINT NOT NULL REFERENCES customer_profile(id) ON DELETE RESTRICT,
    redeemed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (coupon_id, customer_id)
);

