CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_refresh_token_user_active ON refresh_token(user_id, expires_at, revoked_at);

CREATE TABLE otp_challenge (
    challenge_id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    code_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    verified_at TIMESTAMP,
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_otp_challenge_user_expiry ON otp_challenge(user_id, expires_at);

CREATE TABLE customer_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer_profile(id) ON DELETE CASCADE,
    activity_type VARCHAR(48) NOT NULL,
    summary VARCHAR(240) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_customer_activity_history ON customer_activity(customer_id, created_at);

CREATE TABLE payment_callback (
    callback_id VARCHAR(100) PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES payment_record(id) ON DELETE RESTRICT,
    outcome VARCHAR(16) NOT NULL CHECK (outcome IN ('SUCCEEDED', 'FAILED')),
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

