CREATE TABLE booking_seat_claim (
    catalog_item_id BIGINT NOT NULL REFERENCES booking_catalog_item(id) ON DELETE CASCADE,
    seat_or_slot VARCHAR(40) NOT NULL,
    booking_id BIGINT NOT NULL UNIQUE REFERENCES booking_record(id) ON DELETE CASCADE,
    claimed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (catalog_item_id, seat_or_slot)
);

CREATE TABLE streaming_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE streaming_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES streaming_category(id) ON DELETE RESTRICT,
    content_code VARCHAR(40) NOT NULL UNIQUE,
    title VARCHAR(160) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    content_type VARCHAR(16) NOT NULL CHECK (content_type IN ('MOVIE', 'SERIES', 'CLIP')),
    rating VARCHAR(12) NOT NULL DEFAULT 'GENERAL',
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
    playback_url VARCHAR(500) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE subscription_content_entitlement (
    plan_id BIGINT NOT NULL REFERENCES subscription_plan(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES streaming_category(id) ON DELETE CASCADE,
    PRIMARY KEY (plan_id, category_id)
);

CREATE TABLE streaming_watch_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer_profile(id) ON DELETE CASCADE,
    content_id BIGINT NOT NULL REFERENCES streaming_content(id) ON DELETE CASCADE,
    watched_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    progress_seconds INTEGER NOT NULL DEFAULT 0 CHECK (progress_seconds >= 0)
);

