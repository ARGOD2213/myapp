-- notification-service owns this database exclusively (database-per-service). No other service reads or writes it.
CREATE TABLE notification_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64),
    customer_id BIGINT NOT NULL,           -- a *reference* to core-service's customer; no foreign key across services
    user_id BIGINT,                        -- login identity, used to authorise "my notifications"
    channel VARCHAR(12) NOT NULL CHECK (channel IN ('IN_APP', 'EMAIL', 'SMS')),
    event_type VARCHAR(40) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    subject VARCHAR(160),
    message VARCHAR(1000) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    idempotency_key VARCHAR(120) NOT NULL,
    next_attempt_at TIMESTAMP,
    last_error VARCHAR(250),
    read_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at TIMESTAMP
);

-- idempotent consumer: the same business event delivered twice by Kafka (at-least-once) creates one row
CREATE UNIQUE INDEX uq_notification_idempotency ON notification_record(customer_id, idempotency_key);
CREATE INDEX idx_notification_user_created ON notification_record(user_id, created_at DESC);
CREATE INDEX idx_notification_delivery ON notification_record(status, next_attempt_at);
CREATE INDEX idx_notification_created ON notification_record(created_at DESC);
