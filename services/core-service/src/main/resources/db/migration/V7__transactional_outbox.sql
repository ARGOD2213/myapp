-- V7: transactional outbox. Business transactions insert an event row in the SAME transaction as their state
-- change; a relay publishes unpublished rows to Kafka (at-least-once). Notifications are owned by
-- notification-service from this version on; notification_record here is LEGACY (kept for the data
-- migration in scripts/migrate-notifications.ps1 and dropped by a later migration).
CREATE TABLE outbox_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(40) NOT NULL,
    aggregate_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    payload JSONB NOT NULL,
    correlation_id VARCHAR(64),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP
);

CREATE INDEX idx_outbox_unpublished ON outbox_event(id) WHERE published_at IS NULL;

COMMENT ON TABLE notification_record IS 'LEGACY since V7: owned by notification-service (own database). Do not write.';
