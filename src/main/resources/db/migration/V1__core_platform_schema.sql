CREATE INDEX idx_recharge_status_created ON recharge_transaction(status, created_at);
CREATE INDEX idx_payment_customer_created ON payment_record(customer_id, created_at);
CREATE INDEX idx_payment_status_created ON payment_record(status, created_at);
CREATE INDEX idx_subscription_customer_status ON customer_subscription(customer_id, status);
CREATE INDEX idx_subscription_expiry ON customer_subscription(status, expires_at);
CREATE INDEX idx_booking_customer_created ON booking_record(customer_id, created_at);
CREATE INDEX idx_booking_item_status ON booking_record(catalog_item_id, status);
CREATE INDEX idx_ticket_status_priority ON support_ticket(status, priority, created_at);
CREATE INDEX idx_ticket_assignee_status ON support_ticket(assigned_user_id, status);
CREATE INDEX idx_notification_customer_created ON notification_record(customer_id, created_at);
CREATE INDEX idx_audit_entity_created ON audit_event(entity_type, entity_id, created_at);

